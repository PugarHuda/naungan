    <div class="eyebrow">Private by construction</div>
    <h2 class="big">Donors see that it worked. Nobody sees who was helped.</h2>
    <p class="intro">Anyone can recompute “N unique households paid, X disbursed” from public events. The link between a family and its money never exists on-chain.</p>
    <div class="split">
      <div class="panel ledger"><h3>What the chain proves</h3><ul>
        <li>Unique households paid <span class="yes">✓ public</span></li>
        <li>Total funded and disbursed <span class="yes">✓ public</span></li>
        <li>When and why the trigger fired <span class="yes">✓ public</span></li>
        <li>No one claimed twice <span class="yes">✓ public</span></li>
      </ul></div>
      <div class="panel ledger"><h3>What it never learns</h3><ul>
        <li>Names, ID numbers, locations <span class="no">✗ never</span></li>
        <li>Which agency serves which family <span class="no">✗ never</span></li>
        <li>Which family received which payout <span class="no">✗ never</span></li>
        <li>Any agency’s beneficiary list <span class="no">✗ never</span></li>
      </ul></div>
