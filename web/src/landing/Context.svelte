    <div>
      <div class="eyebrow">Why Singapore</div>
      <h2 class="big">Singapore already funds Sumatra’s floods.</h2>
      <p class="intro" style="margin-bottom:0">Naungan is not a fix for Singapore at home: its flash floods drain in under an hour and PUB forecasts them. It fits Singapore as a donor and humanitarian hub. A new 100% tax deduction (OHAS, 2025–2028) rewards overseas emergency cash given through designated charities with strong controls on fund flows, and Naungan gives such a charity a public ledger, a proof check for every payout and registered agencies on-chain. It is a tool for those charities, not a charity itself.</p>
